from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from tracex import __version__
from tracex.core.findings import build_summary
from tracex.core.models import ModuleResult


def to_json(results: list[ModuleResult]) -> str:
    payload = {
        "tool": "TraceX",
        "version": __version__,
        "summary": build_summary(results),
        "results": [r.to_dict() for r in results],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False)


def _md_value(value: Any, indent: int = 0) -> list[str]:
    pad = "  " * indent
    lines: list[str] = []
    if isinstance(value, dict):
        for k, v in value.items():
            if isinstance(v, (dict, list)) and v:
                lines.append(f"{pad}- **{k}**:")
                lines.extend(_md_value(v, indent + 1))
            else:
                lines.append(f"{pad}- **{k}**: {v if v not in ([], {}, None) else '-'}")
    elif isinstance(value, list):
        for item in value:
            if isinstance(item, (dict, list)):
                lines.append(f"{pad}-")
                lines.extend(_md_value(item, indent + 1))
            else:
                lines.append(f"{pad}- {item}")
    else:
        lines.append(f"{pad}- {value}")
    return lines


def _md_findings(findings: list[dict]) -> list[str]:
    lines = ["| Severity | Finding | Detail | Fix |", "|---|---|---|---|"]
    for f in findings:
        cell = lambda t: str(t or "").replace("|", "\\|").replace("\n", " ")
        lines.append(f"| {f['severity']} | {cell(f['title'])} | {cell(f['detail'])} | {cell(f['fix'])} |")
    return lines


def to_markdown(results: list[ModuleResult]) -> str:
    summary = build_summary(results)
    out = ["# TraceX report", "", f"_Generated by TraceX {__version__}_", ""]

    if summary["total_findings"] or any("findings" in r.data for r in results if r.ok):
        c = summary["counts"]
        out += [
            f"**Security grade: {summary['grade']}** ({summary['score']}/100) — "
            f"{c['high']} high, {c['medium']} medium, {c['low']} low, {c['info']} info",
            "",
        ]
        if summary["top_actions"]:
            out.append("### Fix first")
            for i, a in enumerate(summary["top_actions"], 1):
                out.append(f"{i}. **[{a['severity']}] {a['title']}** — {a['fix']}")
            out.append("")

    for r in results:
        out.append(f"## {r.module} — `{r.target}`")
        out.append(f"_{r.timestamp}_")
        out.append("")
        if not r.ok:
            out.append(f"**Error:** {r.error}")
        else:
            data = dict(r.data)
            findings = data.pop("findings", None)
            out.extend(_md_value(data))
            if findings:
                out += ["", "### Findings", ""] + _md_findings(findings)
        out.append("")
    return "\n".join(out)


def write_report(results: list[ModuleResult], path: str | Path) -> Path:
    path = Path(path)
    suffix = path.suffix.lower()
    if suffix == ".json":
        content = to_json(results)
    elif suffix in (".md", ".markdown"):
        content = to_markdown(results)
    else:
        raise ValueError("Output file must end in .json or .md")
    path.write_text(content + "\n", encoding="utf-8")
    return path
